@app.route("/api/live-search")
def live_search():
    """Server-side live search.

    It refreshes the sources first, then applies the user's query on the
    newly fetched information and on the historical GitHub data.
    """
    q = (request.args.get("q") or "").strip()
    if not q:
        return jsonify({"ok": False, "error": "Le paramètre q est obligatoire."}), 400
    try:
        refresh_result = _refresh_live_sources()
        data = _merged_data()
        # Reuse request args through the same filter helper.
        filtered = _filter_items(data.get("items", []))
        return jsonify({
            "ok": True,
            "refresh": refresh_result,
            "count": len(filtered),
            "items": filtered,
        })
    except Exception as exc:
        return jsonify({"ok": False, "error": repr(exc)}), 500


