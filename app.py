
import os
import json
import threading
from datetime import datetime, timezone
from pathlib import Path

import requests
from flask import Flask, jsonify, render_template, request

from scripts import collector

BASE = Path(__file__).resolve().parent
LOCAL_DATA = BASE / "docs" / "data.json"
CONFIG = json.loads((BASE / "config" / "watch_config.json").read_text(encoding="utf-8"))

# Public GitHub repository data updated by GitHub Actions.
DEFAULT_RAW_DATA_URL = (
    "https://raw.githubusercontent.com/"
    "francinegaelle/cyberwatch-horizons/main/docs/data.json"
)
RAW_DATA_URL = os.getenv("RAW_DATA_URL", DEFAULT_RAW_DATA_URL)

app = Flask(__name__, template_folder="templates")

_cache_lock = threading.Lock()
_live_cache = {
    "generated_at": None,
    "items": [],
    "errors": [],
}


def _local_data():
    try:
        return json.loads(LOCAL_DATA.read_text(encoding="utf-8"))
    except Exception:
        return {"generated_at": None, "errors": [], "metrics": {}, "kpis": {}, "items": [], "config": CONFIG}


def _repository_data():
    """Load the latest data generated by GitHub Actions.

    This intentionally reads the public raw GitHub file at request time,
    so the Render app can display new collected data without being redeployed.
    """
    try:
        r = requests.get(
            RAW_DATA_URL,
            params={"ts": int(datetime.now(timezone.utc).timestamp())},
            headers={"Cache-Control": "no-cache", "User-Agent": "CyberWatch-Horizons-Render/1.0"},
            timeout=15,
        )
        r.raise_for_status()
        data = r.json()
        data.setdefault("config", CONFIG)
        return data
    except Exception as exc:
        data = _local_data()
        data.setdefault("errors", [])
        data["errors"] = list(data["errors"]) + [f"GitHub data: {exc!r}"]
        return data


def _merged_data():
    base = _repository_data()
    with _cache_lock:
        live = dict(_live_cache)
    by_id = {x.get("id"): x for x in base.get("items", []) if x.get("id")}
    for item in live.get("items", []):
        if item.get("id"):
            by_id[item["id"]] = item
    items = list(by_id.values())
    items.sort(key=lambda x: x.get("published", ""), reverse=True)
    base["items"] = items[:2500]
    if live.get("generated_at"):
        base["live_refresh_at"] = live["generated_at"]
    base.setdefault("errors", [])
    base["errors"] = list(base["errors"]) + list(live.get("errors", []))
    return base


def _filter_items(items):
    q = (request.args.get("q") or "").strip().lower()
    horizon = (request.args.get("horizon") or "").strip().upper()
    priority = (request.args.get("priority") or "").strip().upper()
    category = (request.args.get("category") or "").strip()
    source = (request.args.get("source") or "").strip()
    try:
        limit = min(max(int(request.args.get("limit", "300")), 1), 1000)
    except ValueError:
        limit = 300

    def keep(x):
        if horizon and x.get("horizon") != horizon:
            return False
        if priority and x.get("priority") != priority:
            return False
        if category and x.get("category") != category:
            return False
        if source and x.get("source") != source:
            return False
        if q:
            hay = " ".join(
                str(x.get(k, ""))
                for k in ("title", "description", "source", "category", "horizon", "priority", "cves")
            ).lower()
            if q not in hay:
                return False
        return True

    return [x for x in items if keep(x)][:limit]


def _refresh_live_sources():
    collected = []
    errors = []
    for src in collector.SOURCES:
        try:
            if src["id"] == "cisa-kev":
                collector.fetch_cisa(src, collected)
            elif src["id"] == "nvd":
                collector.fetch_nvd(src, collected)
            else:
                collector.fetch_feed(src, collected)
        except Exception as exc:
            errors.append(f'{src["name"]}: {exc!r}')

    # Deduplicate and cross-check within this live batch.
    unique = {}
    for item in collected:
        unique[item["id"]] = item
    collected = list(unique.values())
    collector.add_cross_check(collected)
    collected.sort(key=lambda x: x.get("published", ""), reverse=True)

    with _cache_lock:
        _live_cache["generated_at"] = datetime.now(timezone.utc).isoformat()
        _live_cache["items"] = collected[:1200]
        _live_cache["errors"] = errors

    return {
        "generated_at": _live_cache["generated_at"],
        "count": len(collected),
        "errors": errors,
    }


@app.route("/")
def index():
    return render_template("index.html")


@app.route("/api/health")
def health():
    return jsonify({
        "status": "ok",
        "mode": "dynamic",
        "server_time": datetime.now(timezone.utc).isoformat(),
        "raw_data_url": RAW_DATA_URL,
    })


@app.route("/api/summary")
def summary():
    data = _merged_data()
    items = data.get("items", [])
    categories = {}
    sources = {}
    for x in items:
        categories[x.get("category", "Autre")] = categories.get(x.get("category", "Autre"), 0) + 1
        sources[x.get("source", "Inconnue")] = sources.get(x.get("source", "Inconnue"), 0) + 1

    return jsonify({
        "generated_at": data.get("generated_at"),
        "live_refresh_at": data.get("live_refresh_at"),
        "errors": data.get("errors", []),
        "config": data.get("config", CONFIG),
        "metrics": data.get("metrics", {}),
        "kpis": data.get("kpis", {}),
        "counts": {
            "total": len(items),
            "p1": sum(1 for x in items if x.get("priority") == "P1"),
            "p2": sum(1 for x in items if x.get("priority") == "P2"),
            "sources": len(sources),
        },
        "categories": categories,
        "sources": sources,
    })


@app.route("/api/events")
def events():
    data = _merged_data()
    filtered = _filter_items(data.get("items", []))
    return jsonify({
        "count": len(filtered),
        "items": filtered,
    })


@app.route("/api/refresh", methods=["POST"])
def refresh():
    """Perform a real, server-side refresh of the configured public sources."""
    try:
        result = _refresh_live_sources()
        return jsonify({"ok": True, **result})
    except Exception as exc:
        return jsonify({"ok": False, "error": repr(exc)}), 500


@app.route("/api/live-search")
def live_search():
    """Server-side live search.

    It refreshes the sources first, then applies the user's query on the
    newly fetched information and on the historical GitHub data.
    """
    q = (request.args.get("q") or "").strip()
    if not q:
        return jsonify({"ok": False, "error": "Le paramètre q est obligatoire."}), 400
    try:
        refresh_result = _refresh_live_sources()
        data = _merged_data()
        # Reuse request args through the same filter helper.
        filtered = _filter_items(data.get("items", []))
        return jsonify({
            "ok": True,
            "refresh": refresh_result,
            "count": len(filtered),
            "items": filtered,
        })
    except Exception as exc:
        return jsonify({"ok": False, "error": repr(exc)}), 500


@app.route("/api/notification-status")
def notification_status():
    # Never reveal secret values; only whether the server was configured.
    required = ["SMTP_HOST", "SMTP_USER", "SMTP_PASSWORD", "ALERT_EMAIL"]
    configured = all(bool(os.getenv(k)) for k in required)
    return jsonify({
        "email_configured_on_render": configured,
        "github_actions_email": "Les alertes automatiques sont prévues dans le workflow GitHub Actions.",
        "immediate_priorities": CONFIG.get("notifications", {}).get("email", {}).get("immediate_priorities", ["P1", "P2"]),
    })


if __name__ == "__main__":
    port = int(os.getenv("PORT", "10000"))
    app.run(host="0.0.0.0", port=port, debug=False)
